"""Architecture documentation drift test.

Ensures that docs/ARCHITECTURE.md exactly matches the output generated by
scripts/gen_docs.py. If routes, modules, schemas, or security invariants change
without regenerating architecture documentation, this test fails.
"""
from __future__ import annotations

from pathlib import Path

from scripts.gen_docs import OUTPUT_FILE, generate_architecture_markdown


def test_architecture_documentation_no_drift():
    assert OUTPUT_FILE.exists(), f"Architecture documentation missing at {OUTPUT_FILE}"
    expected_content = generate_architecture_markdown().strip()
    actual_content = OUTPUT_FILE.read_text(encoding="utf-8").strip()

    # Verify matching contents
    assert (
        actual_content == expected_content
    ), "docs/ARCHITECTURE.md has drifted from codebase reality. Run `python scripts/gen_docs.py` to update."
